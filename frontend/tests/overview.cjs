const data={sheets,filename:'test',updatedAt:null,asOf:'',accessibleTabs:[0,5,8],segmentMap:{}};
let model=overviewModel(data);
assert.deepEqual([model.stocked,model.empty,model.unknown],[1,2,4]);
assert.ok(Math.abs(model.coverage-100/3)<1e-10);assert.equal(model.purchaseLines,1);
