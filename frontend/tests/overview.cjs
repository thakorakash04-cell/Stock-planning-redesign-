const assert=require('node:assert/strict'),fs=require('node:fs'),ts=require('typescript');
require.extensions['.ts']=(m,n)=>m._compile(ts.transpileModule(fs.readFileSync(n,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,n);
const {overviewModel,salesActivity}=require('../src/overview-model.ts');
const sheets=Array.from({length:7},(_,i)=>({name:String(i),headers:[],rows:[]}));
sheets[0]={name:'Summary',headers:['Material','Source.Name','Current Stock'],rows:[['A','One',5],['B','One',0],['C','Two',-2],['D','Two',null],['E','Two',''],['F','Two',NaN],['G','Two',Infinity]]};
